"use strict";
const assert = require("node:assert/strict");
const { runFreePrologDiagnostic } = require("./free-prolog-diagnostic");

(async () => {
  const program = `person(ada).\nperson(bob).\nready(ada).\nready(bob).\nall_ready :- forall(person(X), ready(X)).\n`;
  const observed = await runFreePrologDiagnostic({ caseId: "ordinary-prolog", program, query: "all_ready", timeoutMs: 1500 });
  assert.equal(observed.status, "observed-not-scored");
  assert.equal(observed.runtime.trust, "untrusted");
  assert.equal(observed.runtime.transcript.exitCode, 0);
  assert.equal(observed.execution_outcome, "succeeded");
  assert.equal(observed.program, program);
  const semanticProgram = `check(Status, Certificate) :- finite_status([domain(person,[ada])], [atom(paints,[ada]), xor(atom(paints,[ada]), atom(writes,[ada]))], atom(writes,[ada]), 16, Status, Certificate).\n`;
  const semantic = await runFreePrologDiagnostic({ caseId: "preloaded-semantics", program: semanticProgram, query: "check(Status, Certificate)", timeoutMs: 1500 });
  assert.equal(semantic.execution_outcome, "succeeded");
  assert.match(semantic.runtime.transcript.transcript, /PAM_DIAGNOSTIC_BINDINGS: check\(contradicted,/);
  const surfaceProgram = `domain(person, [ada]).\naxiom(fact(paints(ada))).\naxiom(fact(xor(paints(ada), writes(ada)))).\n`;
  const surface = await runFreePrologDiagnostic({ caseId: "surface-semantics", program: surfaceProgram, query: "semantic_status(writes(ada), Status, Certificate)", timeoutMs: 1500 });
  assert.equal(surface.execution_outcome, "succeeded");
  assert.match(surface.runtime.transcript.transcript, /semantic_status\(writes\(ada\),contradicted,/);
  const sliced = await runFreePrologDiagnostic({ caseId: "sliced-semantics", program: surfaceProgram, query: "semantic_slice_status(writes(ada), Status, Certificate)", timeoutMs: 1500 });
  assert.equal(sliced.execution_outcome, "succeeded");
  assert.match(sliced.runtime.transcript.transcript, /semantic_slice_status\(writes\(ada\),contradicted,sliced/);
  const traceProgram = `axiom(s1, fact(calm(ada))).\naxiom(s2, rule([calm(X)], ready(X))).\n`;
  const trace = await runFreePrologDiagnostic({ caseId: "audited-forward-trace", program: traceProgram, query: "audit_trace(ready(ada), Result)", timeoutMs: 1500 });
  assert.equal(trace.execution_outcome, "succeeded");
  assert.match(trace.runtime.transcript.transcript, /audit_trace\(ready\(ada\),proof\(ready\(ada\),step\(s2,\[fact\(s1\)\]\)\)\)/);
  const counterProgram = `domain(person, [michelle]).\naxiom(s1, fact(inspires(michelle))).\naxiom(s2, fact(joy(michelle))).\naxiom(s3, rule([creative(michelle)], xor(inspires(michelle), joy(michelle)))).\n`;
  const counter = await runFreePrologDiagnostic({ caseId: "labelled-xor-countermodel", program: counterProgram, query: "labelled_semantic_status(creative(michelle), Status, Certificate)", timeoutMs: 1500 });
  assert.equal(counter.execution_outcome, "succeeded");
  assert.match(counter.runtime.transcript.transcript, /labelled_semantic_status\(creative\(michelle\),contradicted,source_trace\(source_axioms\(\[s1,s2,s3\]\)/);
  console.log("free-prolog-diagnostic ok: ordinary agent-style Prolog executes as isolated non-scoring evidence");
})().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
